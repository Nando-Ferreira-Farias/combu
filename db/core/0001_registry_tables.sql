-- combu-db core 0001: the entity registry's tables.
--
-- Datasets, entity types, entities and their claims, hierarchies with their rules, aliases and
-- geometry (combu/README.md). Every fact table has a validity period, and every fact key but
-- the alias key includes the owning dataset, so each source keeps its own versions.
-- Temporal keys (WITHOUT OVERLAPS, PERIOD) need PostgreSQL 18; btree_gist gives them GiST
-- operator classes for scalar columns.

CREATE EXTENSION IF NOT EXISTS btree_gist;
CREATE EXTENSION IF NOT EXISTS postgis;

CREATE SCHEMA registry;  -- tables, functions and triggers
CREATE SCHEMA asof;      -- generated point-in-time views, one per entity type

CREATE TABLE registry.dataset (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY,
    key TEXT NOT NULL,
    kind TEXT NOT NULL,
    priority SMALLINT NOT NULL,
    description TEXT DEFAULT '' NOT NULL,
    CONSTRAINT pk_dataset PRIMARY KEY (id),
    CONSTRAINT ck_dataset_kind CHECK (kind IN ('curated', 'source', 'derived')),
    CONSTRAINT uq_dataset_key UNIQUE (key)
);

CREATE TABLE registry.entity_type (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY,
    code TEXT NOT NULL,
    parent_id SMALLINT,
    name TEXT NOT NULL,
    is_abstract BOOLEAN DEFAULT false NOT NULL,
    CONSTRAINT pk_entity_type PRIMARY KEY (id),
    CONSTRAINT fk_entity_type_parent_id_entity_type FOREIGN KEY(parent_id) REFERENCES registry.entity_type (id),
    CONSTRAINT uq_entity_type_code UNIQUE (code)
);

CREATE TABLE registry.hierarchy (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY,
    code TEXT NOT NULL,
    name TEXT NOT NULL,
    description TEXT DEFAULT '' NOT NULL,
    CONSTRAINT pk_hierarchy PRIMARY KEY (id),
    CONSTRAINT uq_hierarchy_code UNIQUE (code)
);

CREATE TABLE registry.entity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    type_id SMALLINT NOT NULL,
    key TEXT NOT NULL,
    name TEXT NOT NULL,
    lifetime TSTZRANGE NOT NULL,
    CONSTRAINT pk_entity PRIMARY KEY (id),
    CONSTRAINT uq_entity_id UNIQUE (id, lifetime WITHOUT OVERLAPS),
    CONSTRAINT ck_entity_lifetime_not_empty CHECK (NOT isempty(lifetime)),
    CONSTRAINT fk_entity_type_id_entity_type FOREIGN KEY(type_id) REFERENCES registry.entity_type (id),
    CONSTRAINT uq_entity_key UNIQUE (key)
);

CREATE INDEX ix_entity_type_id ON registry.entity (type_id);

CREATE TABLE registry.hierarchy_rule (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY,
    hierarchy_id SMALLINT NOT NULL,
    parent_type_id SMALLINT,
    child_type_id SMALLINT NOT NULL,
    CONSTRAINT pk_hierarchy_rule PRIMARY KEY (id),
    CONSTRAINT fk_hierarchy_rule_child_type_id_entity_type FOREIGN KEY(child_type_id) REFERENCES registry.entity_type (id),
    CONSTRAINT fk_hierarchy_rule_hierarchy_id_hierarchy FOREIGN KEY(hierarchy_id) REFERENCES registry.hierarchy (id),
    CONSTRAINT fk_hierarchy_rule_parent_type_id_entity_type FOREIGN KEY(parent_type_id) REFERENCES registry.entity_type (id),
    CONSTRAINT uq_hierarchy_rule_hierarchy_id UNIQUE NULLS NOT DISTINCT (hierarchy_id, parent_type_id, child_type_id)
);

CREATE TABLE registry.entity_alias (
    scheme TEXT NOT NULL,
    code TEXT NOT NULL,
    valid TSTZRANGE NOT NULL,
    entity_id BIGINT NOT NULL,
    dataset_id SMALLINT NOT NULL,
    CONSTRAINT pk_entity_alias PRIMARY KEY (scheme, code, valid WITHOUT OVERLAPS),
    CONSTRAINT fk_entity_alias_entity_id_entity FOREIGN KEY (entity_id, PERIOD valid) REFERENCES registry.entity (id, PERIOD lifetime) DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT ck_entity_alias_valid_not_empty CHECK (NOT isempty(valid)),
    CONSTRAINT fk_entity_alias_dataset_id_dataset FOREIGN KEY(dataset_id) REFERENCES registry.dataset (id)
);

CREATE INDEX ix_entity_alias_entity_id ON registry.entity_alias (entity_id);

CREATE TABLE registry.entity_claim (
    entity_id BIGINT NOT NULL,
    dataset_id SMALLINT NOT NULL,
    name TEXT NOT NULL,
    lifetime TSTZRANGE NOT NULL,
    CONSTRAINT pk_entity_claim PRIMARY KEY (entity_id, dataset_id),
    CONSTRAINT ck_entity_claim_lifetime_not_empty CHECK (NOT isempty(lifetime)),
    CONSTRAINT fk_entity_claim_dataset_id_dataset FOREIGN KEY(dataset_id) REFERENCES registry.dataset (id),
    CONSTRAINT fk_entity_claim_entity_id_entity FOREIGN KEY(entity_id) REFERENCES registry.entity (id)
);

CREATE INDEX ix_entity_claim_dataset_id ON registry.entity_claim (dataset_id);

CREATE TABLE registry.entity_geometry (
    entity_id BIGINT NOT NULL,
    role TEXT NOT NULL,
    valid TSTZRANGE NOT NULL,
    geom geometry(GEOMETRY,4326) NOT NULL,
    dataset_id SMALLINT NOT NULL,
    CONSTRAINT pk_entity_geometry PRIMARY KEY (entity_id, role, dataset_id, valid WITHOUT OVERLAPS),
    CONSTRAINT fk_entity_geometry_entity_id_entity FOREIGN KEY (entity_id, PERIOD valid) REFERENCES registry.entity (id, PERIOD lifetime) DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT ck_entity_geometry_role CHECK (role IN ('location', 'boundary', 'display')),
    CONSTRAINT ck_entity_geometry_valid_not_empty CHECK (NOT isempty(valid)),
    CONSTRAINT fk_entity_geometry_dataset_id_dataset FOREIGN KEY(dataset_id) REFERENCES registry.dataset (id)
);

CREATE INDEX idx_entity_geometry_geom ON registry.entity_geometry USING gist (geom);

CREATE TABLE registry.hierarchy_edge (
    hierarchy_id SMALLINT NOT NULL,
    child_id BIGINT NOT NULL,
    valid TSTZRANGE NOT NULL,
    parent_id BIGINT,
    dataset_id SMALLINT NOT NULL,
    CONSTRAINT pk_hierarchy_edge PRIMARY KEY (hierarchy_id, child_id, dataset_id, valid WITHOUT OVERLAPS),
    CONSTRAINT fk_hierarchy_edge_child_id_entity FOREIGN KEY (child_id, PERIOD valid) REFERENCES registry.entity (id, PERIOD lifetime) DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT fk_hierarchy_edge_parent_id_entity FOREIGN KEY (parent_id, PERIOD valid) REFERENCES registry.entity (id, PERIOD lifetime) DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT ck_hierarchy_edge_valid_not_empty CHECK (NOT isempty(valid)),
    CONSTRAINT ck_hierarchy_edge_not_own_parent CHECK (parent_id <> child_id),
    CONSTRAINT fk_hierarchy_edge_dataset_id_dataset FOREIGN KEY(dataset_id) REFERENCES registry.dataset (id),
    CONSTRAINT fk_hierarchy_edge_hierarchy_id_hierarchy FOREIGN KEY(hierarchy_id) REFERENCES registry.hierarchy (id)
);

CREATE INDEX ix_hierarchy_edge_parent_id ON registry.hierarchy_edge (parent_id);
